import { test, expect } from '@playwright/test';
import { validateStacksAddress } from '@stacks/transactions';
test('opt-in real UI receipt and public testnet payment smoke', async ({ page, request }) => {
  test.skip(process.env.OSSR_LIVE_SMOKE !== '1', 'Enable only after a manual wallet-driven testnet run.');
  const ui = new URL(process.env.OSSR_LIVE_UI_URL ?? '');
  const relay = new URL(process.env.OSSR_LIVE_RELAY_URL ?? 'https://relay.ossr.network');
  expect(ui.protocol).toBe('https:'); expect(relay.protocol).toBe('https:');
  expect(ui.username + ui.password + relay.username + relay.password).toBe('');
  if (!process.env.OSSR_LIVE_STORAGE_STATE) throw new Error('Export the real UI browser storage state after the manual wallet run. No synthetic receipt is created by this test.');
  const txid = process.env.OSSR_LIVE_TXID ?? '';
  expect(txid).toMatch(/^0x[0-9a-f]{64}$/i);
  const recipient = process.env.OSSR_LIVE_RECIPIENT ?? '';
  expect(validateStacksAddress(recipient) && /^(ST|SN)/.test(recipient)).toBe(true);
  const amount = process.env.OSSR_LIVE_AMOUNT_SATS ?? '';
  const fee = process.env.OSSR_LIVE_FEE_SATS ?? '';
  expect(amount).toMatch(/^[1-9][0-9]*$/); expect(fee).toMatch(/^[1-9][0-9]*$/);
  const infoResponse = await request.get(new URL('/v1/info', relay).href);
  expect(infoResponse.ok()).toBe(true);
  const info = await infoResponse.json();
  expect(info.network).toBe('testnet');
  await page.route('**/*', route => {
    // This smoke is read-only; wallet signing and broadcasting happened manually.
    if (route.request().method() !== 'GET') return route.abort();
    return route.continue();
  });
  await page.goto(new URL('/dashboard', ui).href);
  await expect(page.getByText('MOCKED DEMO', { exact: false })).toHaveCount(0);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ossr-ui:submitted-transfer') ?? 'null'));
  expect(saved).not.toBeNull();
  expect(saved.response.transaction_id.replace(/^0x/, '').toLowerCase()).toBe(txid.slice(2).toLowerCase());
  expect(saved.intent.recipient).toBe(recipient);
  expect(saved.intent.amountSats).toBe(amount);
  expect(saved.quote.quote.sponsorFee).toBe(fee);
  expect(saved.quote.quote.sponsorPrincipal).toBe(info.sponsorPrincipal);
  expect(saved.quote.quote.network).toBe('testnet');
  const response = await request.get(`https://api.testnet.hiro.so/extended/v1/tx/${txid}`);
  expect(response.ok()).toBe(true);
  const tx = await response.json();
  expect(tx.tx_status).toBe('success'); expect(tx.sponsored).toBe(true);
  expect(tx.sender_address).toBe(saved.intent.origin);
  expect(tx.sponsor_address).toBe(info.sponsorPrincipal);
  expect(tx.contract_call.contract_id).toBe(saved.quote.quote.adapterContract);
  expect(tx.contract_call.function_name).toBe('sponsored-transfer');
  expect(BigInt(tx.fee_rate)).toBeGreaterThan(0n);
  const transfers = (tx.events ?? []).filter((event: { event_type: string }) => event.event_type === 'fungible_token_asset').map((event: { fungible_token_asset: unknown }) => event.fungible_token_asset) as { asset_event_type: string; asset_id: string; sender: string; recipient: string; amount: string }[];
  const asset = `${saved.quote.quote.reimbursementAsset.contract}::sbtc-token`;
  const payment = (to: string, sats: string) => transfers.some(event => event.asset_event_type === 'transfer' && event.asset_id === asset && event.sender === saved.intent.origin && event.recipient === to && event.amount === sats);
  expect(payment(recipient, amount)).toBe(true);
  expect(payment(info.sponsorPrincipal, fee)).toBe(true);
  await expect(page.locator(`a[href*="${txid}"]`).first()).toHaveAttribute('href', /chain=testnet/);
  await page.reload();
  await expect(page.locator(`a[href*="${txid}"]`).first()).toBeVisible();
});
